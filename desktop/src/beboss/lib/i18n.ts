const normalize = (value: string) => value.trim().replace(/\s+/g, " ");
const nodeOriginals = new WeakMap<Text, { original: string; rendered: string }>();
const attributeOriginals = new WeakMap<Element, Map<string, { original: string; rendered: string }>>();
function translate(value: string, language: DesktopLanguage): string {
  if (language === "en") return value;
  const normalized = normalize(value);
  const translated = DICTIONARY[language][normalized];
  if (!translated) return value;
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  return leading + translated + trailing;
}
function translateTextNode(node: Text, language: DesktopLanguage) {
  const current = node.nodeValue ?? "";
  if (!current.trim()) return;
  const previous = nodeOriginals.get(node);
  const original = previous && current === previous.rendered ? previous.original : current;
  const rendered = translate(original, language);
  nodeOriginals.set(node, { original, rendered });
  if (rendered !== current) node.nodeValue = rendered;
}
function translateElement(element: Element, language: DesktopLanguage) {
  if (element.closest("script,style,textarea,pre,code,[data-no-translate]")) return;
  const attributes = ["placeholder", "title", "aria-label"];
  let cache = attributeOriginals.get(element);
  if (!cache) { cache = new Map(); attributeOriginals.set(element, cache); }
  for (const attribute of attributes) {
    const current = element.getAttribute(attribute);
    if (!current) continue;
    const previous = cache.get(attribute);
    const original = previous && current === previous.rendered ? previous.original : current;
    const rendered = translate(original, language);
    cache.set(attribute, { original, rendered });
    if (rendered !== current) element.setAttribute(attribute, rendered);
  }
}
function translateSubtree(root: Node, language: DesktopLanguage) {
  if (root.nodeType === Node.TEXT_NODE) { translateTextNode(root as Text, language); return; }
  if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return;
  const element = root.nodeType === Node.ELEMENT_NODE ? root as Element : null;
  if (element?.closest("script,style,textarea,pre,code,[data-no-translate]")) return;
  if (element) translateElement(element, language);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node: Node | null;
  while ((node = walker.nextNode())) translateTextNode(node as Text, language);
  if (element) element.querySelectorAll("*").forEach((child) => translateElement(child, language));
}
export function applyDesktopLanguage(root: HTMLElement, language: DesktopLanguage): () => void {
  document.documentElement.lang = language;
  translateSubtree(root, language);
  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === "characterData" && mutation.target instanceof Text) translateTextNode(mutation.target, language);
      for (const added of Array.from(mutation.addedNodes)) translateSubtree(added, language);
      if (mutation.type === "attributes" && mutation.target instanceof Element) translateElement(mutation.target, language);
    }
  });
  observer.observe(root, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ["placeholder", "title", "aria-label"] });
  return () => observer.disconnect();
}
